const BY_ID = new Map(SOURCE_REGISTRY.map((s) => [s.id, s]));

export function getSource(id) {
  return BY_ID.get(id) || null;
}

export function listSources(filter = {}) {
  return SOURCE_REGISTRY.filter((s) => {
    if (filter.category && s.category !== filter.category) return false;
    if (filter.authorityTier && s.authorityTier !== filter.authorityTier) return false;
    if (filter.country && s.geographicCoverage !== "global" && s.geographicCoverage !== "corridor" && s.geographicCoverage !== filter.country && s.geographicCoverage !== "project-context" && s.geographicCoverage !== "SITE") {
      return false;
    }
    return true;
  });
}

export function sourcesRequiringAttribution(ids) {
  const set = new Set(ids || []);
  return SOURCE_REGISTRY.filter((s) => set.has(s.id) && s.attributionRequired);
}

export function sourceRegistrySnapshot() {
  return SOURCE_REGISTRY.map((s) => ({ ...s, parameters: [...s.parameters] }));
}
