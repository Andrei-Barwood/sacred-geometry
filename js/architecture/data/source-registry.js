function src(partial) {
  return Object.freeze({
    id: partial.id,
    name: partial.name,
    organization: partial.organization,
    category: partial.category,
    authorityTier: partial.authorityTier,
    homepage: partial.homepage || null,
    geographicCoverage: partial.geographicCoverage || "corridor",
    temporalCoverage: partial.temporalCoverage || null,
    updateFrequency: partial.updateFrequency || null,
    license: partial.license || null,
    attributionRequired: partial.attributionRequired === true,
    retrievalMethod: partial.retrievalMethod || "manual-catalog",
    notes: partial.notes || "",
    parameters: Object.freeze(partial.parameters || []),
  });
}

